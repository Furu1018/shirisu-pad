-- Phase: 模擬の編成スロットを 3 → 2 に戻す
-- ============================================================================
-- 適用: Supabase Dashboard → SQL Editor で実行 (冪等・再実行安全)
--
-- なぜ戻すか:
--   30 で 2→3 に増やした動機は「レベル数 × 編成数」を1スロット1行で持つ必要が
--   あったから。31 でレベルが levels JSONB としてスロットの**中**に入り、
--   「1スロット = 1編成」になったので、スロット数は編成の多様性だけで決められる。
--   3枠は模擬タブのカードを重くするだけなので2枠に戻す (ユーザー決定 2026-08-12)。
--
-- ⚠ 破壊的: slot>=3 の行を削除する。
--   適用時点の本番は **1行だけ** (ふるり / water / 30B / levels={"3":30} /
--   編成: アニス:スター・クラウン・スノーホワイト：ヘビーアームズ・プリバティ・
--   エレグ：ブーム・アンド・ショック) で、2026-08-11 の動作確認データ。
--   残したい編成が slot>=3 にある場合は、**先に UI で slot 1/2 へ入れ直してから**
--   この SQL を実行すること。
-- ============================================================================

-- ---- 1) 3枠目の提出を削除 ----
-- CHECK を張り替える前に消しておく (残っていると制約追加が失敗する)
DELETE FROM player_damages WHERE slot >= 3;

-- ---- 2) CHECK を 1|2 に戻す ----
ALTER TABLE player_damages DROP CONSTRAINT IF EXISTS chk_player_damages_slot;
ALTER TABLE player_damages
    ADD CONSTRAINT chk_player_damages_slot CHECK (slot IN (1, 2));

NOTIFY pgrst, 'reload schema';
