-- ============================================================================
-- 適用: Supabase Dashboard → SQL Editor で実行 (冪等・再実行安全)
--
-- 何が変わるか:
--   第44回 (2026-09-05) は当日2回「配信中止」が押され、published_plans の行ごと削除された。
--   その結果 08:34〜17:04 の **8.5時間メンバーは自分の割当を見られず**、
--   plan_acks も一緒に消えたので、次に配信し直しても更新通知が誰にも飛ばなかった。
--
--   中止を「消す」から **「組み直し中として凍結する」** に変える (ユーザー決定 2026-09-07:
--   「運営が組み直し中と出るほうが良い。出ないとメンバーがほっとかれていると感じる」)。
--
--   frozen_at TIMESTAMPTZ  凍結した時刻 (NULL = 配信中)
--   frozen_by TEXT         凍結した運営の表示名
--
--   あわせて **配信履歴を消さない** ようにする (クライアント側の変更)。
--   旧クライアントは配信のたびに古い行を削除していたので、
--   「前回の配信と比べて誰の割当が変わったか」を後から再現できなかった。
--   行が増えても読みは常に「season_id が同じ中で id 最大の1件」なので影響はない。
--
-- ADD COLUMN (NULL 既定) はメタデータ変更のみで既存行の書き換えは無いが、
-- ACCESS EXCLUSIVE ロックを一瞬取る。長いトランザクションが掴んでいたら待たずに失敗させる。
-- 2列は1つの ALTER で足す (片方だけ入る部分適用状態を作らない)。
--
-- 未適用の環境: 凍結の読み書きだけが静かに劣化する
--   (取得は frozen 列なしで再試行し「常に配信中」扱い / 凍結操作はエラーで適用を案内)。
-- ============================================================================

SET lock_timeout = '3s';

ALTER TABLE published_plans
    ADD COLUMN IF NOT EXISTS frozen_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS frozen_by TEXT;

-- 「そのシーズンの最新の配信」を引く読み方に合わせた索引 (履歴を消さなくなるため行数が増える)
CREATE INDEX IF NOT EXISTS idx_published_plans_season_id_desc
    ON published_plans(season_id, id DESC);

NOTIFY pgrst, 'reload schema';   -- API に即認識させる (忘れると列が見えず 38未適用扱いのまま)
